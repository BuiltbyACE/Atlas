-- ─────────────────────────────────────────────────────────────
-- Atlas foundation (Phase 0)
--
-- Creates the schemas named in docs/ATLAS.md §10.1 and the one table Phase 0
-- actually needs: outbox.events (§7.1), the only interface between Go and the
-- Elixir orchestrator (ADR-005).
--
-- Domain tables (people.*, core.user_accounts, audit.events, ...) are Phase 1
-- work (§10.3, Appendix A). This migration deliberately stops at the event
-- spine so Phase 0 stays small and verifiable.
-- ─────────────────────────────────────────────────────────────

CREATE SCHEMA IF NOT EXISTS core;
CREATE SCHEMA IF NOT EXISTS people;
CREATE SCHEMA IF NOT EXISTS audit;
CREATE SCHEMA IF NOT EXISTS outbox;
-- The Elixir orchestrator owns its own schema (Oban jobs, workflow instances,
-- consumer cursors, processed events — §10.1). Creating it here lets the
-- migration grant atlas_orchestrator the privileges it needs; Elixir's Ecto
-- migrations own the tables inside it.
CREATE SCHEMA IF NOT EXISTS orchestrator;

COMMENT ON SCHEMA outbox IS 'Transactional outbox: Go writes, Elixir reads (ADR-005).';
COMMENT ON SCHEMA orchestrator IS 'Elixir orchestrator state: jobs, workflows, cursors (atlas_orchestrator owns it).';

-- ── outbox.events — the write side of the event spine ────────
CREATE TABLE outbox.events (
  seq            bigserial PRIMARY KEY,          -- global order for consumers
  id             uuid NOT NULL UNIQUE,           -- event id (UUIDv7, generated by Go)
  type           text NOT NULL,                  -- e.g. 'core.system.hello.v1'
  aggregate_type text NOT NULL,                  -- e.g. 'system'
  aggregate_id   uuid NOT NULL,
  occurred_at    timestamptz NOT NULL DEFAULT now(),
  actor_id       uuid,
  correlation_id uuid,                           -- ties a chain of events together
  causation_id   uuid,                           -- the event/command that caused this one
  payload        jsonb NOT NULL
);

-- Consumers page by seq; this index keeps "events for one aggregate" queries cheap.
CREATE INDEX events_aggregate_idx ON outbox.events (aggregate_type, aggregate_id);
CREATE INDEX events_occurred_at_idx ON outbox.events (occurred_at);

-- Retention target (§7.1): rows older than the retention window are archived
-- here. Same shape as events, no trigger.
CREATE TABLE outbox.events_archive (LIKE outbox.events INCLUDING ALL);

COMMENT ON TABLE outbox.events IS 'Append-only event log written in the same transaction as the business change.';

-- ── NOTIFY trigger — wake the consumer ───────────────────────
-- Elixir LISTENs on atlas_outbox and also polls as a safety net (§7.1), so a
-- missed notification can never lose an event.
CREATE FUNCTION outbox.notify_event() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_notify('atlas_outbox', NEW.seq::text);
  RETURN NEW;
END;
$$;

CREATE TRIGGER events_notify
  AFTER INSERT ON outbox.events
  FOR EACH ROW EXECUTE FUNCTION outbox.notify_event();

-- ── Grants (docs/ATLAS.md §10.1, §13.3) ──────────────────────
-- Roles are created by infra/compose/postgres/initdb.d/01-roles.sh in local
-- development and by the platform in staging/production. The role may not
-- exist in a bare throwaway database (e.g. a migration test), so every grant
-- is guarded rather than assumed.
DO $$
DECLARE
  r text;
BEGIN
  -- Go services: full DML on the schemas they own, append to the outbox.
  FOREACH r IN ARRAY ARRAY['atlas_api', 'atlas_worker'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('GRANT USAGE ON SCHEMA core, people, audit, outbox TO %I', r);
      EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA outbox TO %I', r);
      EXECUTE format('GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA outbox TO %I', r);
    END IF;
  END LOOP;

  -- Orchestrator: read-only on outbox, full control of its own schema.
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'atlas_orchestrator') THEN
    GRANT USAGE ON SCHEMA outbox TO atlas_orchestrator;
    GRANT SELECT ON ALL TABLES IN SCHEMA outbox TO atlas_orchestrator;
    GRANT USAGE, CREATE ON SCHEMA orchestrator TO atlas_orchestrator;
  END IF;

  -- Reporting/BI: read-only.
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'atlas_readonly') THEN
    GRANT USAGE ON SCHEMA core, people, audit, outbox, orchestrator TO atlas_readonly;
    GRANT SELECT ON ALL TABLES IN SCHEMA outbox TO atlas_readonly;
  END IF;
END
$$;

