-- ─────────────────────────────────────────────────────────────
-- Atlas foundation — Phase 1 (§10.3, §6.1–§6.7)
--
-- The tables every later module depends on: identity (people.persons +
-- core.user_accounts/sessions), authorisation (roles, permissions, grants,
-- service identities), the approval spine, the append-only audit log, and the
-- small pieces of core infrastructure named in §10.1 that the first module
-- needs: runtime settings, human-reference sequences, notifications and files.
--
-- Conventions (§6.6) applied throughout:
--   * UUIDv7 primary keys, generated by Go (no DB default).
--   * citext for email, so case does not matter.
--   * soft delete via archived_at; updated_at maintained by a trigger.
--   * optimistic locking via a `version` column where records are edited.
--
-- Modules create their own schemas (crm, work, contracts, finance, systems,
-- units, intel, integrations) with their own migrations; this migration only
-- lays the shared foundation in core / people / audit.
-- ─────────────────────────────────────────────────────────────

-- citext is a trusted extension (PG13+), so the migrator may install it.
CREATE EXTENSION IF NOT EXISTS citext;

COMMENT ON SCHEMA core IS 'Core: accounts, sessions, roles, grants, settings, approvals, notifications, files, sequences (atlas_api).';
COMMENT ON SCHEMA people IS 'People: persons, departments (atlas_api).';
COMMENT ON SCHEMA audit IS 'Append-only audit trail: insert-only for every role (§6.3).';

-- ── updated_at bookkeeping (§6.6) ────────────────────────────
CREATE FUNCTION core.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- ── people: departments and persons ──────────────────────────
CREATE TABLE people.departments (
  id             uuid PRIMARY KEY,
  name           text NOT NULL UNIQUE,
  lead_person_id uuid,                                 -- set once persons exist
  created_at     timestamptz NOT NULL DEFAULT now(),
  archived_at    timestamptz
);

CREATE TABLE people.persons (
  id              uuid PRIMARY KEY,
  full_name       text NOT NULL,
  work_email      citext UNIQUE,
  phone_e164      text,
  whatsapp_e164   text,
  employment_type text NOT NULL CHECK (employment_type IN ('full_time','part_time','contractor','intern','external')),
  department_id   uuid REFERENCES people.departments(id),
  line_manager_id uuid REFERENCES people.persons(id),
  status          text NOT NULL DEFAULT 'active' CHECK (status IN ('onboarding','active','on_leave','exited')),
  start_date      date,
  end_date        date,
  version         int NOT NULL DEFAULT 1,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX persons_department_idx ON people.persons (department_id);
CREATE INDEX persons_status_idx ON people.persons (status);

CREATE TRIGGER persons_touch_updated_at
  BEFORE UPDATE ON people.persons
  FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();

COMMENT ON TABLE people.persons IS 'One row per human in Atlas; a user account links to exactly one person.'; 

-- ── core: accounts and sessions ──────────────────────────────
CREATE TABLE core.user_accounts (
  id                  uuid PRIMARY KEY,
  person_id           uuid NOT NULL UNIQUE REFERENCES people.persons(id),
  email               citext NOT NULL UNIQUE,
  password_hash       text,                            -- argon2id; null if SSO-only
  mfa_totp_secret_enc bytea,                           -- encrypted at application level
  mfa_required        boolean NOT NULL DEFAULT false,
  status              text NOT NULL CHECK (status IN ('invited','active','suspended','deactivated')),
  last_login_at       timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE core.sessions (
  id           uuid PRIMARY KEY,
  user_id      uuid NOT NULL REFERENCES core.user_accounts(id),
  token_hash   bytea NOT NULL UNIQUE,                  -- opaque token, stored hashed
  mfa_verified boolean NOT NULL DEFAULT false,
  ip           inet,
  user_agent   text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL,
  revoked_at   timestamptz
);
CREATE INDEX sessions_user_idx ON core.sessions (user_id);
CREATE INDEX sessions_expires_idx ON core.sessions (expires_at);

-- ── core: RBAC ───────────────────────────────────────────────
CREATE TABLE core.roles (
  key         text PRIMARY KEY,                        -- 'ceo_commercial', …
  name        text NOT NULL,
  description text
);

CREATE TABLE core.permissions (
  key         text PRIMARY KEY,                        -- 'crm.lead.write', …
  description text,
  sensitive   boolean NOT NULL DEFAULT false           -- gated behind *.sensitive.read rules
);

CREATE TABLE core.role_permissions (
  role_key       text NOT NULL REFERENCES core.roles(key) ON DELETE CASCADE,
  permission_key text NOT NULL REFERENCES core.permissions(key) ON DELETE CASCADE,
  PRIMARY KEY (role_key, permission_key)
);

CREATE TABLE core.role_grants (
  id         uuid PRIMARY KEY,
  user_id    uuid NOT NULL REFERENCES core.user_accounts(id),
  role_key   text NOT NULL REFERENCES core.roles(key),
  scope_type text NOT NULL CHECK (scope_type IN ('company','business_unit','department','project','own')),
  scope_id   uuid,                                     -- null for company/own
  granted_by uuid NOT NULL,
  granted_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);
CREATE INDEX role_grants_user_idx ON core.role_grants (user_id);
CREATE INDEX role_grants_role_idx ON core.role_grants (role_key);

CREATE TABLE core.service_identities (
  id              text PRIMARY KEY,                    -- 'svc:orchestrator'
  description     text,
  permissions     text[] NOT NULL,
  credential_hash bytea NOT NULL,
  rotated_at      timestamptz NOT NULL,
  disabled_at     timestamptz
);

-- ── core: approvals ──────────────────────────────────────────
CREATE TABLE core.approval_policies (
  id               uuid PRIMARY KEY,
  decision_type    text NOT NULL,                      -- 'expense','purchase','discount',…
  min_amount_minor bigint,
  max_amount_minor bigint,
  currency         char(3),
  approver_rule    text NOT NULL,                      -- 'line_manager','domain_ceo','both_ceos',…
  effective_from   timestamptz NOT NULL,
  effective_to     timestamptz
);

CREATE TABLE core.approvals (
  id              uuid PRIMARY KEY,
  subject_type    text NOT NULL,
  subject_id      uuid NOT NULL,
  requested_by    uuid NOT NULL,
  policy_id       uuid REFERENCES core.approval_policies(id),
  status          text NOT NULL CHECK (status IN ('pending','approved','rejected','expired','cancelled')),
  subject_version int NOT NULL,                        -- approval invalid if the subject changes
  created_at      timestamptz NOT NULL DEFAULT now(),
  decided_at      timestamptz
);
CREATE INDEX approvals_status_idx ON core.approvals (status);
CREATE INDEX approvals_subject_idx ON core.approvals (subject_type, subject_id);
CREATE INDEX approvals_requested_by_idx ON core.approvals (requested_by);

CREATE TABLE core.approval_decisions (
  approval_id uuid NOT NULL REFERENCES core.approvals(id) ON DELETE CASCADE,
  approver_id uuid NOT NULL,
  decision    text NOT NULL CHECK (decision IN ('approve','reject')),
  comment     text,
  decided_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (approval_id, approver_id)
);
CREATE INDEX approval_decisions_approver_idx ON core.approval_decisions (approver_id);

-- ── core: settings (§6.7) and human references (§6.6) ────────
CREATE TABLE core.settings (
