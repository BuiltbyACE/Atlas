CREATE TRIGGER settings_touch
  BEFORE UPDATE ON core.settings
  FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();

-- Per-type, per-year counters behind human references (LEAD-2026-0042, …).
CREATE TABLE core.sequences (
  ref_type   text NOT NULL,
  ref_year   int NOT NULL,
  last_value bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (ref_type, ref_year)
);

CREATE FUNCTION core.next_reference(p_type text, p_year int) RETURNS text
LANGUAGE plpgsql AS $$
DECLARE
  v bigint;
BEGIN
  INSERT INTO core.sequences (ref_type, ref_year, last_value)
  VALUES (p_type, p_year, 1)
  ON CONFLICT (ref_type, ref_year)
  DO UPDATE SET last_value = core.sequences.last_value + 1
  RETURNING last_value INTO v;

  RETURN format('%s-%s-%s', upper(p_type), p_year, lpad(v::text, 4, '0'));
END;
$$;

-- ── core: notifications (§6.4) ───────────────────────────────
CREATE TABLE core.notifications (
  id                  uuid PRIMARY KEY,
  recipient_person_id uuid NOT NULL REFERENCES people.persons(id),
  channel             text NOT NULL CHECK (channel IN ('in_app','email','whatsapp','sms')),
  template            text,
  subject             text,
  body                text,
  payload             jsonb,
  entity_type         text,
  entity_id           uuid,
  status              text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent','delivered','failed','read')),
  attempts            int NOT NULL DEFAULT 0,
  last_error          text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  sent_at             timestamptz,
  read_at             timestamptz
);
CREATE INDEX notifications_recipient_idx ON core.notifications (recipient_person_id, created_at DESC);
CREATE INDEX notifications_status_idx ON core.notifications (status);

CREATE TABLE core.notification_attempts (
  id              bigserial PRIMARY KEY,
  notification_id uuid NOT NULL REFERENCES core.notifications(id) ON DELETE CASCADE,
  channel         text NOT NULL,
  provider        text,
  provider_ref    text,
  status          text NOT NULL,
  error           text,
  attempted_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notification_attempts_notification_idx ON core.notification_attempts (notification_id);

-- ── core: files / evidence metadata (§6.5) ───────────────────
CREATE TABLE core.files (
  id             uuid PRIMARY KEY,
  bucket         text NOT NULL,
  object_key     text NOT NULL,
  filename       text NOT NULL,
  content_type   text NOT NULL,
  size_bytes     bigint NOT NULL,
  checksum_sha256 text,
  classification text NOT NULL DEFAULT 'internal' CHECK (classification IN ('public','internal','confidential','restricted')),
  status         text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','available','quarantined','deleted')),
  uploaded_by    uuid,
  entity_type    text,
  entity_id      uuid,
  created_at     timestamptz NOT NULL DEFAULT now(),
  archived_at    timestamptz,
  UNIQUE (bucket, object_key)
);
CREATE INDEX files_entity_idx ON core.files (entity_type, entity_id);

-- ── audit: append-only event log (§6.3) ──────────────────────
CREATE TABLE audit.events (
  id           uuid PRIMARY KEY,
  occurred_at  timestamptz NOT NULL DEFAULT now(),
  actor_type   text NOT NULL,                          -- 'user','service','system'
  actor_id     text NOT NULL,
  on_behalf_of uuid,
  action       text NOT NULL,
  entity_type  text NOT NULL,
  entity_id    uuid,
  before       jsonb,
  after        jsonb,
  reason       text,
  request_id   text,
  ip           inet,
  user_agent   text
);
CREATE INDEX audit_events_occurred_idx ON audit.events (occurred_at);
CREATE INDEX audit_events_entity_idx ON audit.events (entity_type, entity_id);
CREATE INDEX audit_events_actor_idx ON audit.events (actor_id);

CREATE FUNCTION audit.forbid_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit.events is append-only';
END;
$$;

CREATE TRIGGER audit_no_update
  BEFORE UPDATE OR DELETE ON audit.events
  FOR EACH ROW EXECUTE FUNCTION audit.forbid_change();

-- ── Grants (§10.1, §13.3) ────────────────────────────────────
-- Roles are created by infra/compose/postgres/initdb.d/01-roles.sh locally and
-- by the platform elsewhere; every grant is guarded so a bare database still
-- migrates. audit.events gets SELECT + INSERT only — never UPDATE/DELETE.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'atlas_api') THEN
    GRANT USAGE ON SCHEMA core, people, audit, outbox TO atlas_api;
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA core, people TO atlas_api;
    GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA audit TO atlas_api;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA core, people, audit, outbox TO atlas_api;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA core GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO atlas_api;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA people GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO atlas_api;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA audit GRANT SELECT, INSERT ON TABLES TO atlas_api;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA core, people GRANT USAGE, SELECT ON SEQUENCES TO atlas_api;
  END IF;

  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'atlas_worker') THEN
    GRANT USAGE ON SCHEMA core, people, audit, outbox TO atlas_worker;
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA core, people TO atlas_worker;
    GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA audit TO atlas_worker;
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA core, people, audit, outbox TO atlas_worker;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA core GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO atlas_worker;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA people GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO atlas_worker;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA audit GRANT SELECT, INSERT ON TABLES TO atlas_worker;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA core, people GRANT USAGE, SELECT ON SEQUENCES TO atlas_worker;
  END IF;

  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'atlas_readonly') THEN
    GRANT USAGE ON SCHEMA core, people, audit, outbox TO atlas_readonly;
    GRANT SELECT ON ALL TABLES IN SCHEMA core, people, audit, outbox TO atlas_readonly;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA core, people, audit GRANT SELECT ON TABLES TO atlas_readonly;
  END IF;

  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'atlas_orchestrator') THEN
    GRANT USAGE ON SCHEMA core, people TO atlas_orchestrator;
    GRANT SELECT ON ALL TABLES IN SCHEMA core, people TO atlas_orchestrator;
    ALTER DEFAULT PRIVILEGES FOR ROLE atlas_migrator IN SCHEMA core, people GRANT SELECT ON TABLES TO atlas_orchestrator;
  END IF;
END
$$;

