// Package outbox writes domain events to outbox.events in the same transaction
// as the business change (docs/ATLAS.md §7.1, ADR-005).
//
// This is the only interface between Go and the Elixir orchestrator. Go records
// facts; Elixir reacts. Nothing here talks to Elixir directly.
package outbox

import (
	"encoding/json"
	"fmt"
	"time"

	"github.com/google/uuid"
)

// Event types emitted by Atlas. The catalogue grows per module (§7.4); this
// constant set is the Phase 0 spine only.
const (
	// TypeSystemHelloV1 is the Phase 0 smoke event: proof that the whole path
	// Go → outbox → Elixir → browser works end to end (Appendix A).
	TypeSystemHelloV1 = "core.system.hello.v1"
)

// Aggregate types (the "aggregate" part of an event type, §7.2).
const (
	AggregateSystem = "system"
)

// Event is a row in outbox.events. It mirrors the table exactly so the writer
// stays a thin, obvious mapping (§7.1).
type Event struct {
	ID            uuid.UUID  // UUIDv7, generated by Go
	Type          string     // module.aggregate.past_tense_verb.vN
	AggregateType string     // e.g. "system"
	AggregateID   uuid.UUID  // the entity the event is about
	OccurredAt    time.Time  // when the fact happened (UTC)
	ActorID       *uuid.UUID // who caused it; nil for system actions
	CorrelationID *uuid.UUID // ties a chain of events together
	CausationID   *uuid.UUID // the event/command that caused this one
	Payload       []byte     // jsonb
}

// HelloPayload is the body of core.system.hello.v1.
type HelloPayload struct {
	Message   string    `json:"message"`
	GreetedAt time.Time `json:"greeted_at"`
}

// NewHello builds a core.system.hello.v1 event. A hello has no real aggregate,
// so its aggregate id is its own event id — a stable, unique anchor that keeps
// the schema valid without inventing a domain entity.
func NewHello(actorID, correlationID *uuid.UUID, message string) (Event, error) {
	id, err := uuid.NewV7()
	if err != nil {
		return Event{}, fmt.Errorf("generate event id: %w", err)
	}
	now := time.Now().UTC()

	payload, err := json.Marshal(HelloPayload{Message: message, GreetedAt: now})
	if err != nil {
		return Event{}, fmt.Errorf("marshal hello payload: %w", err)
	}

	return Event{
		ID:            id,
		Type:          TypeSystemHelloV1,
		AggregateType: AggregateSystem,
		AggregateID:   id,
		OccurredAt:    now,
		ActorID:       actorID,
		CorrelationID: correlationID,
		Payload:       payload,
	}, nil
}

// DecodePayload unmarshals the event payload into dst. Handy for tests and for
// internal callers that want the typed body rather than raw JSON.
func (e Event) DecodePayload(dst any) error {
	if err := json.Unmarshal(e.Payload, dst); err != nil {
		return fmt.Errorf("decode %s payload: %w", e.Type, err)
	}
	return nil
}
